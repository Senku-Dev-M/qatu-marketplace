"""Download curated demo product photos and connect them to the seed catalog.

Sources are recorded in product_image_sources.json. Run from any directory.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "scripts" / "product_image_sources.json"
CATALOG = ROOT / "scripts" / "seed_catalog.json"
OUTPUT = ROOT / "web" / "public" / "products"
MODULE = ROOT / "web" / "src" / "seed-images.js"


def main() -> None:
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    image_by_product = {(item["name"], item["presentation"]): item for item in sources}
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for item in catalog:
        source = image_by_product[(item["name"], item["presentation"])]
        destination = OUTPUT / source["file"]
        if not destination.exists():
            subprocess.run(["curl.exe", "-fsSL", "--max-time", "30", source["url"], "-o", str(destination)], check=True)
        data = destination.read_bytes()
        if not data.startswith(b"\xff\xd8\xff") or len(data) > 5_000_000:
            raise ValueError(f"Invalid JPEG or file too large: {destination}")
        item["imageFile"] = source["file"]
        print(f"{source['file']}: {len(data)} bytes")
    CATALOG.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    mapping = {f"{item['name']}|{item['presentation']}": f"/products/{item['imageFile']}" for item in catalog}
    MODULE.write_text("// Generated by scripts/prepare_product_images.py\n"
                      + "const images = " + json.dumps(mapping, ensure_ascii=False, indent=2) + "\n\n"
                      + "export function seedImage(product) {\n"
                      + "  return images[`${product.name}|${product.presentation}`] || null\n"
                      + "}\n", encoding="utf-8")


if __name__ == "__main__":
    main()
